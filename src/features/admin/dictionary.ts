/** Translate a French action/validation message for display. */
export function translateMessage(message: string, lang: AdminLang): string {
  if (lang === "fr") return message;
  const known = MESSAGES[message];
  if (known) return known[lang];
  const max = /^(\d[\d\s ]*) caractères maximum\.$/.exec(message);
  if (max) return lang === "en" ? `${max[1]} characters maximum.` : `${max[1]} حرف كحد أقصى.`;
  return message;
}

export function translateErrors(errors: Record<string, string>, lang: AdminLang): Record<string, string> {
  if (lang === "fr") return errors;
  return Object.fromEntries(Object.entries(errors).map(([key, value]) => [key, translateMessage(value, lang)]));
}

const DATE_LOCALES: Record<AdminLang, string> = { fr: "fr-MA", en: "en-GB", ar: "ar-MA" };

export function formatAdminDateTime(value: string | null | undefined, lang: AdminLang): string {
  if (!value) return "—";
  return new Intl.DateTimeFormat(DATE_LOCALES[lang], { dateStyle: "medium", timeStyle: "short", timeZone: "Africa/Casablanca", numberingSystem: "latn" }).format(new Date(value));
}

export function formatAdminDate(value: string, lang: AdminLang): string {
  return new Intl.DateTimeFormat(DATE_LOCALES[lang], { dateStyle: "medium", numberingSystem: "latn" }).format(new Date(value));
}

export function formatAdminNumber(value: number, lang: AdminLang): string {
  return new Intl.NumberFormat(DATE_LOCALES[lang], { numberingSystem: "latn" }).format(value);
}
